// 문항이 기대하는 답안의 '형태'를 교사 모범답안에서 판정한다.
//
// 왜 코드가 판정하는가:
//   채점 척도가 모든 답을 서술형으로 가정하고 있어서, "경복궁"이나
//   "암술, 수술, 꽃받침, 꽃잎"처럼 낱말·나열이 정답인 문항에서는 교사 모범답안을
//   그대로 낸 학생조차 2점을 받았다("핵심 단어 위주로만 작성").
//   실측(2026-08-26): 단답형 표본 6개 중 4개가 그랬고, 서술형 대조군은 2/2 만점.
//
//   이 형태 판정을 모델에게 맡기면 채점할 때마다 새로 내려져, 같은 문항인데
//   학생마다 다른 기준이 적용될 수 있다. 평가에서 기준이 흔들리는 건 점수가
//   짜거나 후한 것보다 나쁘다. 그래서 모델에게 묻지 않고 여기서 정한다.
//
//   근거로 삼는 건 교사가 이미 등록한 모범답안이다. "이 문항의 만점은 이렇게
//   생겼다"를 교사가 이미 알려준 셈이므로, 새로 추측할 이유가 없다.

export type AnswerForm = "낱말" | "나열" | "구" | "서술";

// 한국어 문장 종결 형태. 평서형 '~다', 높임 '~요/~습니다', 물음표·느낌표까지.
const SENTENCE_END = /(다|요|까|죠|네|군요|습니다|입니다)[.!?]?$|[.!?]$/;

/** 모범답안의 형태를 판정한다. 모범답안이 없으면 null (형태를 단정하지 않음). */
export function detectAnswerForm(modelAnswer: string | undefined | null): AnswerForm | null {
  const a = (modelAnswer || "").trim();
  if (!a) return null;

  // 여러 문장이면 명백한 서술
  if ((a.match(/[.!?]/g) || []).length >= 2) return "서술";
  if (SENTENCE_END.test(a)) return "서술";

  // 종결어미가 없는 답. 길면 서술로 보되(문장부호를 안 찍었을 뿐일 수 있다),
  // 짧으면 낱말·구·나열이다.
  if (a.length > 60) return "서술";
  if (/[,、·]/.test(a)) return "나열";
  return a.length <= 8 ? "낱말" : "구";
}

/**
 * 채점 프롬프트에 넣을 형태 안내 문장. 모범답안이 없으면 빈 문자열
 * (없는 기준을 지어내지 않는다 — 그땐 지침의 일반 척도로 채점된다).
 */
export function answerFormHint(modelAnswer: string | undefined | null): string {
  const form = detectAnswerForm(modelAnswer);
  if (!form) return "";

  if (form === "서술") {
    return "기대하는 답안 형태: 문장 서술. 완성된 문장으로 서술했는지를 채점에 반영합니다. 단, 교사 모범답안이 담고 있는 것까지만 요구합니다.";
  }
  const label = { 낱말: "낱말", 나열: "낱말 나열", 구: "짧은 구(句)" }[form];
  return `기대하는 답안 형태: ${label}. 이 문항의 정답은 완성된 문장이 아니라 ${label} 형태입니다. 교사 모범답안과 같은 내용을 ${label} 형태로 정확히 답했다면 4점입니다. '완성된 문장이 아니다', '설명이 부족하다'는 이유로 감점하지 않습니다.`;
}
